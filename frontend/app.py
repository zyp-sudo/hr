class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        parsed = urlparse(self.path)
        query = parse_qs(parsed.query)
        page = query.get("page", [parsed.path.strip("/") or "dashboard"])[0]
        routes = {
            "dashboard": dashboard,
            "results": results_page,
            "architecture": architecture_page,
            "graph": graph_page,
            "evolution": evolution_page,
            "quality": quality_page,
            "etl": etl_page,
            "samples": samples_page,
            "real_jobs": real_jobs_page,
            "settings": settings_page,
        }
        if page == "match":
            body = match_page(query, "")
        elif page == "dashboard":
            body = dashboard(query)
        elif page == "evolution":
            body = evolution_page(query)
        elif page == "quality":
            body = quality_page(query)
        elif page == "etl":
            body = etl_page(query)
        elif page == "real_jobs":
            body = real_jobs_page(query)
        else:
            body = routes.get(page, dashboard)()
        self.respond(body)

    def do_POST(self):
        parsed = urlparse(self.path)
        query = parse_qs(parsed.query)
        length = int(self.headers.get("Content-Length", "0"))
        body = self.rfile.read(length).decode("utf-8")
        page = query.get("page", [""])[0]
        if page == "match":
            self.respond(match_page(query, body))
        elif page == "settings":
            self.respond(settings_page(body))
        else:
            self.send_response(404)
            self.end_headers()

    def log_message(self, format, *args):
        return

    def respond(self, body):
        data = body.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Cache-Control", "public, max-age=10")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)


if __name__ == "__main__":
    server = ThreadingHTTPServer(("localhost", PORT), Handler)
    print(f"Python frontend listening on http://localhost:{PORT}")
    server.serve_forever()
