# Thread-safe API response cache with TTL
_cache = {}
_cache_lock = threading.Lock()
CACHE_TTL = 30  # seconds — data is static CSV-backed, safe to cache
_executor = ThreadPoolExecutor(max_workers=4)


def api_json(path, method="GET", payload=None):
    cache_key = f"{method}:{path}:{json.dumps(payload) if payload else ''}"
    now = time.time()
    with _cache_lock:
        entry = _cache.get(cache_key)
        if entry and (now - entry["ts"]) < CACHE_TTL:
            return entry["data"]

    data = None
    headers = {"Content-Type": "application/json"}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(API_BASE + path, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(request, timeout=10) as response:
            result = json.loads(response.read().decode("utf-8"))
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
        result = {"error": str(exc)}

    with _cache_lock:
        _cache[cache_key] = {"ts": now, "data": result}
    return result


def fetch_all(*calls):
    """Execute multiple api_json calls in parallel and return results in order."""
    futures = {}
    for i, (path, method, payload) in enumerate(calls):
        futures[_executor.submit(api_json, path, method, payload)] = i
    results = [None] * len(calls)
    for future in as_completed(futures):
        results[futures[future]] = future.result()
    return results


def read_local_ai_settings():
    settings = {}
    if not LOCAL_ENV_PATH.exists():
        return settings
    for raw_line in LOCAL_ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line.startswith("$env:") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.replace("$env:", "", 1).strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        settings[key] = value
    return settings


def mask_secret(value):
    if not value:
        return "未设置"
    if len(value) <= 8:
        return "已保存"
    return value[:5] + "..." + value[-4:]


def ps_quote(value):
    return '"' + str(value or "").replace("`", "``").replace('"', '`"') + '"'


def fmt_num(value):
    if isinstance(value, float):
        return f"{value:,.2f}".rstrip("0").rstrip(".")
    try:
        return f"{int(value):,}"
    except (TypeError, ValueError):
        return html.escape(str(value))


def save_local_ai_settings(form):
    current = read_local_ai_settings()
    api_key = form.get("api_key", [""])[0].strip() or current.get("MATCH_AI_API_KEY", "")
    settings = {
        "MATCH_AI_ENABLED": "true" if form.get("enabled", [""])[0] == "on" else "false",
        "MATCH_AI_PROVIDER": form.get("provider", ["deepseek"])[0].strip() or "deepseek",
        "MATCH_AI_API_KEY": api_key,
        "MATCH_AI_BASE_URL": form.get("base_url", ["https://api.deepseek.com"])[0].strip(),
        "MATCH_AI_API_URL": form.get("api_url", [""])[0].strip(),
        "MATCH_AI_MODEL": form.get("model", ["deepseek-chat"])[0].strip() or "deepseek-chat",
        "MATCH_AI_TIMEOUT_SECONDS": form.get("timeout", ["30"])[0].strip() or "30",
    }
    lines = [
        "# Local AI settings generated by the Web settings page.",
        "# This file is ignored by git. Do not commit API keys.",
        "",
    ]
    for key, value in settings.items():
        lines.append(f"$env:{key} = {ps_quote(value)}")
    LOCAL_ENV_PATH.parent.mkdir(parents=True, exist_ok=True)
    LOCAL_ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return settings


def tag_list(items, color="", limit=None):
    if not items:
        return '<span class="muted">无</span>'
    values = list(items)[:limit] if limit else list(items)
    class_name = f"tag {color}".strip()
    return "".join(
        f'<span class="{class_name}" style="font-size:11px;">{html.escape(str(item))}</span>'
        for item in values
    )


def detail_text(value, empty="无"):
    text = str(value or "").strip()
    return html.escape(text if text else empty)


def truncate_text(value, limit=900):
    text = str(value or "").strip()
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + f"\n... 已截断，原文约 {len(text)} 字"


