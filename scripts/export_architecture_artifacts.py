import csv
import json
from datetime import datetime, timezone, timedelta
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
ETL_DIR = DATA_DIR / "etl"
KG_DIR = DATA_DIR / "kg"
WAREHOUSE_DIR = DATA_DIR / "warehouse"

UNIFIED_JOBS_PATH = ETL_DIR / "unified_jobs.csv"
UNIFIED_SKILLS_PATH = ETL_DIR / "unified_job_skills.csv"
QUALITY_PATH = ETL_DIR / "data_quality_report.csv"
NODES_PATH = KG_DIR / "nodes.csv"
EDGES_PATH = KG_DIR / "edges.csv"
TRENDS_PATH = KG_DIR / "skill_trends.csv"

MYSQL_SCHEMA_PATH = WAREHOUSE_DIR / "mysql_schema.sql"
MYSQL_LOAD_PATH = WAREHOUSE_DIR / "mysql_load.sql"
ES_NDJSON_PATH = WAREHOUSE_DIR / "elasticsearch_jobs.ndjson"
CHROMA_DOCS_PATH = WAREHOUSE_DIR / "chroma_documents.jsonl"
NEO4J_CYPHER_PATH = WAREHOUSE_DIR / "neo4j_import.cypher"
MANIFEST_PATH = WAREHOUSE_DIR / "architecture_manifest.json"


def now_iso():
    return datetime.now(timezone(timedelta(hours=8))).isoformat(timespec="seconds")


def read_csv(path):
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8-sig", newline="") as file:
        return list(csv.DictReader(file))


def rel(path):
    return path.relative_to(ROOT).as_posix()


def write_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_json(path, payload):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def text_for_embedding(row):
    parts = [
        row.get("job_title", ""),
        row.get("company", ""),
        row.get("normalized_category", ""),
        row.get("city", ""),
        row.get("responsibility", ""),
        row.get("requirement", ""),
        row.get("normalized_skills", ""),
    ]
    return "\n".join(str(part).strip() for part in parts if str(part).strip())


