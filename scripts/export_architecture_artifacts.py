def export_elasticsearch(jobs):
    ES_NDJSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    with ES_NDJSON_PATH.open("w", encoding="utf-8") as file:
        for row in jobs:
            record_id = row.get("record_id", "")
            doc = {
                "record_id": record_id,
                "title": row.get("job_title", ""),
                "company": row.get("company", ""),
                "city": row.get("city", ""),
                "country": row.get("country", ""),
                "source_id": row.get("source_id", ""),
                "source_name": row.get("source_name", ""),
                "source_type": row.get("source_type", ""),
                "source_url": row.get("source_url", ""),
                "published_at": row.get("published_at", ""),
                "collected_at": row.get("collected_at", ""),
                "normalized_category": row.get("normalized_category", ""),
                "skills": [item for item in row.get("normalized_skills", "").split("|") if item],
                "quality_score": int(row.get("quality_score") or 0),
                "quality_level": row.get("quality_level", ""),
                "text": text_for_embedding(row),
            }
            file.write(json.dumps({"index": {"_index": "job_postings", "_id": record_id}}, ensure_ascii=False) + "\n")
            file.write(json.dumps(doc, ensure_ascii=False) + "\n")


def export_chroma_documents(jobs):
    CHROMA_DOCS_PATH.parent.mkdir(parents=True, exist_ok=True)
    with CHROMA_DOCS_PATH.open("w", encoding="utf-8") as file:
        for row in jobs:
            payload = {
                "id": row.get("record_id", ""),
                "document": text_for_embedding(row),
                "metadata": {
                    "source_id": row.get("source_id", ""),
                    "source_name": row.get("source_name", ""),
                    "source_url": row.get("source_url", ""),
                    "job_title": row.get("job_title", ""),
                    "company": row.get("company", ""),
                    "city": row.get("city", ""),
                    "country": row.get("country", ""),
                    "normalized_category": row.get("normalized_category", ""),
                    "published_at": row.get("published_at", ""),
                    "quality_score": int(row.get("quality_score") or 0),
                    "quality_level": row.get("quality_level", ""),
                },
            }
            file.write(json.dumps(payload, ensure_ascii=False) + "\n")


def build_neo4j_cypher():
    return """// Generated by scripts/export_architecture_artifacts.py
// Copy data/kg/nodes.csv and data/kg/edges.csv into Neo4j import directory first.

CREATE CONSTRAINT kg_node_id IF NOT EXISTS FOR (n:KgNode) REQUIRE n.id IS UNIQUE;

LOAD CSV WITH HEADERS FROM 'file:///nodes.csv' AS row
MERGE (n:KgNode {id: row.id})
SET n.label = row.label,
    n.type = row.type,
    n.canonical = row.canonical,
    n.count = toInteger(row.count),
    n.firstSeen = row.first_seen,
    n.lastSeen = row.last_seen,
    n.propertiesJson = row.properties;

LOAD CSV WITH HEADERS FROM 'file:///edges.csv' AS row
MATCH (a:KgNode {id: row['from']})
MATCH (b:KgNode {id: row['to']})
MERGE (a)-[r:KG_RELATION {id: row.id}]->(b)
SET r.type = row.type,
    r.weight = toInteger(row.weight),
    r.confidence = toFloat(row.confidence),
    r.firstSeen = row.first_seen,
    r.lastSeen = row.last_seen,
    r.evidence = row.evidence;
"""


def build():
    jobs = read_csv(UNIFIED_JOBS_PATH)
    skills = read_csv(UNIFIED_SKILLS_PATH)
    nodes = read_csv(NODES_PATH)
    edges = read_csv(EDGES_PATH)
    trends = read_csv(TRENDS_PATH)
    quality = read_csv(QUALITY_PATH)

    WAREHOUSE_DIR.mkdir(parents=True, exist_ok=True)
    write_text(MYSQL_SCHEMA_PATH, build_mysql_schema())
    write_text(MYSQL_LOAD_PATH, build_mysql_load())
    export_elasticsearch(jobs)
    export_chroma_documents(jobs)
    write_text(NEO4J_CYPHER_PATH, build_neo4j_cypher())

    manifest = {
        "generated_at": now_iso(),
        "inputs": {
            "unified_jobs": rel(UNIFIED_JOBS_PATH),
            "unified_skills": rel(UNIFIED_SKILLS_PATH),
            "kg_nodes": rel(NODES_PATH),
            "kg_edges": rel(EDGES_PATH),
            "skill_trends": rel(TRENDS_PATH),
            "quality_report": rel(QUALITY_PATH),
        },
        "counts": {
            "jobs": len(jobs),
            "skill_evidence": len(skills),
            "kg_nodes": len(nodes),
            "kg_edges": len(edges),
            "skill_trends": len(trends),
            "quality_sources": len(quality),
        },
        "outputs": {
            "mysql_schema": rel(MYSQL_SCHEMA_PATH),
            "mysql_load": rel(MYSQL_LOAD_PATH),
            "elasticsearch_ndjson": rel(ES_NDJSON_PATH),
            "chroma_documents": rel(CHROMA_DOCS_PATH),
            "neo4j_cypher": rel(NEO4J_CYPHER_PATH),
        },
        "notes": [
            "CSV remains the local source of truth for the prototype.",
            "MySQL, Elasticsearch, Neo4j and ChromaDB artifacts are generated for production migration.",
            "Neo4j import uses a generic KG_RELATION type and stores the semantic relation in r.type.",
        ],
    }
    write_json(MANIFEST_PATH, manifest)
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    build()
